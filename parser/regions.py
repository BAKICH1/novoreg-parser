def resolve_region(inn: str = "", ogrn: str = "", address: str = "") -> tuple[str, str]:
    """Определяет код и название региона по ИНН, ОГРН или тексту адреса."""
    candidates: list[str] = []
    if ogrn and len(ogrn) >= 5 and ogrn[:1] in ("1", "3", "5"):
        candidates.append(ogrn[3:5])
    if inn and len(inn) >= 2:
        candidates.append(inn[:2])

    for raw in candidates:
        code = REGION_ALIASES.get(raw, raw)
        if code in REGIONS:
            return code, REGIONS[code]

    if address:
        low = address.lower()
        for city, code in CITY_TO_REGION.items():
            if city in low:
                return code, REGIONS[code]
        for code, rname in REGIONS.items():
            key = rname.lower().replace("г. ", "").replace("республика ", "")
            if len(key) >= 4 and key in low:
                return code, rname

    return "77", REGIONS["77"]


